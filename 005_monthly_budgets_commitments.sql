create table if not exists public.monthly_budgets (
  id bigint generated by default as identity primary key,
  user_id uuid not null references auth.users(id) on delete cascade,
  month_idx integer not null,
  amount numeric(14,2) not null check (amount > 0),
  created_at timestamptz not null default now(),
  updated_at timestamptz not null default now(),
  unique (user_id, month_idx)
);

create table if not exists public.commitments (
  id bigint generated by default as identity primary key,
  user_id uuid not null references auth.users(id) on delete cascade,
  name text not null check (length(trim(name)) > 0),
  provider text not null default 'أخرى',
  total_amount numeric(14,2) not null check (total_amount > 0),
  installment_amount numeric(14,2) not null check (installment_amount > 0),
  installment_count integer not null check (installment_count > 0),
  start_month_idx integer not null,
  -- شهر الاستحقاق الذي أكد المستخدم دفعه؛ لا يغيّر قيمة المصروف المحسوبة.
  paid_months integer[] not null default '{}',
  created_at timestamptz not null default now(),
  constraint commitments_schedule_covers_total
    check (installment_amount * installment_count >= total_amount),
  constraint commitments_previous_installments_below_total
    check (installment_amount * (installment_count - 1) < total_amount)
);

create index if not exists idx_monthly_budgets_user_month
  on public.monthly_budgets(user_id, month_idx);
create index if not exists idx_commitments_user_start
  on public.commitments(user_id, start_month_idx);

alter table public.monthly_budgets enable row level security;
alter table public.commitments enable row level security;

drop policy if exists "Users manage their monthly budgets" on public.monthly_budgets;
create policy "Users manage their monthly budgets"
  on public.monthly_budgets for all
  using (auth.uid() = user_id)
  with check (auth.uid() = user_id);

drop policy if exists "Users manage their commitments" on public.commitments;
create policy "Users manage their commitments"
  on public.commitments for all
  using (auth.uid() = user_id)
  with check (auth.uid() = user_id);

grant select, insert, update, delete on public.monthly_budgets to authenticated;
grant select, insert, update, delete on public.commitments to authenticated;
grant usage, select on sequence public.monthly_budgets_id_seq to authenticated;
grant usage, select on sequence public.commitments_id_seq to authenticated;
